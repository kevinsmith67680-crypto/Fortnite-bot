"""Chest detection in third-person perspective frames (Phase 4).

Three interchangeable methods, all CPU-only and classical:

* ``color``: HSV colour segmentation (gold body, brown lid, cream inside),
  connected components and geometric/structural rules (lid above body, a
  brown-over-gold "seam", plausible aspect ratio).
* ``template``: multi-scale ``TM_CCOEFF_NORMED`` matching of rendered
  reference views over the frame (slow; a baseline).
* ``hybrid`` (default): colour candidates verified against the multi-view
  reference templates *as class-label images*, resized to each candidate.
  This is robust to shading and scale, and the best-matching view tells the
  distance estimator which physical width/height the chest shows.

Templates are generated by ``scripts/generate_templates_3d.py`` from the
controlled environment (ground truth is used only to build that dataset).
The agent's own character is masked out using its known camera rig.
"""

from __future__ import annotations

import json
import math
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Final

import cv2
import numpy as np

from chest_hunter.vision.chest_detector import iou

# OpenCV HSV: H in [0, 180), S and V in [0, 255].
GOLD: Final = ((17, 140, 95), (29, 255, 255))
BROWN: Final = ((8, 185, 30), (18, 255, 165))
CREAM: Final = ((14, 35, 150), (32, 125, 255))
BACKGROUND, GOLD_ID, BROWN_ID, CREAM_ID = 0, 1, 2, 3
METHODS: Final = ("color", "template", "hybrid")
_KERNEL3: Final = np.ones((3, 3), np.uint8)


def segment_classes(hsv: np.ndarray) -> np.ndarray:
    """Per-pixel class image: 1 gold body, 2 brown lid, 3 cream inside, 0 other."""
    out = np.zeros(hsv.shape[:2], np.uint8)
    out[cv2.inRange(hsv, *map(np.array, GOLD)) > 0] = GOLD_ID
    out[cv2.inRange(hsv, *map(np.array, CREAM)) > 0] = CREAM_ID
    out[cv2.inRange(hsv, *map(np.array, BROWN)) > 0] = BROWN_ID
    return out


@dataclass(frozen=True, slots=True)
class Detection3D:
    category: str                         # "chest" or "chest_opened"
    bbox: tuple[int, int, int, int]       # x, y, w, h
    confidence: float
    timestamp: float
    method: str
    view: str = ""                        # best-matching reference view
    width_m: float = 0.9                  # apparent physical width of that view
    height_m: float = 0.65                # apparent physical height of that view
    partial: bool = False                 # cut by the frame edge or the agent

    @property
    def centre(self) -> tuple[float, float]:
        x, y, w, h = self.bbox
        return (x + w / 2.0, y + h / 2.0)

    @property
    def bottom_centre(self) -> tuple[float, float]:
        x, y, w, h = self.bbox
        return (x + w / 2.0, float(y + h))


@dataclass(frozen=True, slots=True)
class Template3D:
    name: str
    category: str
    labels: np.ndarray
    bgr: np.ndarray
    elevation_deg: float
    width_m: float
    height_m: float
    aspect: float


class TemplateSet3D:
    def __init__(self, templates: list[Template3D]) -> None:
        if not templates:
            raise ValueError("no 3D chest templates")
        self.templates = templates

    @classmethod
    def load(cls, directory: str | Path) -> TemplateSet3D:
        directory = Path(directory)
        index = json.loads((directory / "templates.json").read_text(encoding="utf-8"))
        out = []
        for t in index["templates"]:
            labels = cv2.imread(str(directory / f"{t['name']}_labels.png"), cv2.IMREAD_GRAYSCALE)
            bgr = cv2.imread(str(directory / f"{t['name']}.png"), cv2.IMREAD_COLOR)
            if labels is None or bgr is None:
                raise FileNotFoundError(f"template {t['name']} is missing in {directory}")
            out.append(Template3D(t["name"], t["category"], labels, bgr, float(t["elevation_deg"]),
                                  float(t["width_m"]), float(t["height_m"]), float(t["aspect"])))
        return cls(out)


@dataclass(slots=True)
class _Candidate:
    bbox: tuple[int, int, int, int]
    gold: int
    brown: int
    cream: int
    seam: float
    partial: bool
    region: np.ndarray


class ChestDetector3D:
    def __init__(self, templates: TemplateSet3D, *, method: str = "hybrid",
                 min_score: float = 0.5, min_area: int = 10) -> None:
        if method not in METHODS:
            raise ValueError(f"method must be one of {', '.join(METHODS)}")
        self.templates = templates
        self.method = method
        self.min_score = min_score
        self.min_area = min_area
        self.calls = 0
        self.total_seconds = 0.0

    @property
    def mean_ms(self) -> float:
        return 1000.0 * self.total_seconds / max(1, self.calls)

    def detect(self, frame: np.ndarray, timestamp: float, *,
               exclude: tuple[int, int, int, int] | None = None,
               camera_pitch_deg: float | None = None,
               fy: float | None = None) -> list[Detection3D]:
        """Detect chests. ``camera_pitch_deg`` and ``fy`` (from the observation) let the
        hybrid method compare candidates only with views from a similar elevation."""
        started = time.perf_counter()
        if self.method == "template":
            dets = self._detect_template(frame, timestamp, exclude)
        else:
            # A light blur stabilises hue against sensor noise (shaded gold must not
            # flicker into the lid's brown range).
            hsv = cv2.cvtColor(cv2.GaussianBlur(frame, (3, 3), 0), cv2.COLOR_BGR2HSV)
            classes = segment_classes(hsv)
            # ``exclude`` (the agent's own body) is not blanked: its colours never fall in
            # the chest classes, and a chest right next to the agent must stay visible.
            # Candidates touching it are only marked partial.
            cands = self._candidates(classes, exclude)
            dets = []
            for c in cands:
                elevation = None
                if camera_pitch_deg is not None and fy:
                    v = c.bbox[1] + c.bbox[3] / 2.0
                    elevation = -(camera_pitch_deg + math.degrees(
                        math.atan((frame.shape[0] / 2.0 - v) / fy)))
                d = self._classify(classes, c, timestamp, elevation)
                if d is not None:
                    dets.append(d)
            dets = _nms(dets)
        self.calls += 1
        self.total_seconds += time.perf_counter() - started
        return dets

    # -- candidates ---------------------------------------------------------------------------

    def _candidates(self, classes: np.ndarray,
                    exclude: tuple[int, int, int, int] | None) -> list[_Candidate]:
        """Lid-anchored candidates: every brown lid blob seeds one candidate, grown through
        connected gold/cream pixels inside a window below and around the lid. Gold objects
        without a lid (decoys) never seed a candidate, and a chest next to a decoy is not
        merged with it."""
        h_img, w_img = classes.shape
        brown = (classes == BROWN_ID).astype(np.uint8)
        brown = cv2.morphologyEx(brown, cv2.MORPH_CLOSE, _KERNEL3)
        count, _, stats, _ = cv2.connectedComponentsWithStats(brown, connectivity=8)
        out = []
        for i in range(1, count):
            bx, by, bw, bh, area = (int(v) for v in stats[i])
            if area < 3:
                continue
            x0 = max(0, int(bx - 0.15 * bw) - 1)
            x1 = min(w_img, int(bx + bw + 0.15 * bw) + 2)
            y0 = max(0, int(by - 0.3 * bh) - 1)
            y1 = min(h_img, int(by + bh + max(1.2 * bh, 0.9 * bw)) + 2)
            window = classes[y0:y1, x0:x1]
            obj = (window > 0).astype(np.uint8)
            obj = cv2.morphologyEx(obj, cv2.MORPH_CLOSE, _KERNEL3)
            n2, lab2, st2, _ = cv2.connectedComponentsWithStats(obj, connectivity=8)
            seed = lab2[by - y0:by - y0 + bh, bx - x0:bx - x0 + bw]
            ids = np.unique(seed[(window[by - y0:by - y0 + bh, bx - x0:bx - x0 + bw] == BROWN_ID)])
            ids = ids[ids > 0]
            if ids.size == 0:
                continue
            member = np.isin(lab2, ids) & (window > 0)
            ys, xs = np.nonzero(member)
            if xs.size < self.min_area:
                continue
            cx0, cx1, cy0, cy1 = int(xs.min()), int(xs.max()) + 1, int(ys.min()), int(ys.max()) + 1
            region = np.where(member[cy0:cy1, cx0:cx1], window[cy0:cy1, cx0:cx1], 0).astype(np.uint8)
            gold = int(np.count_nonzero(region == GOLD_ID))
            brown_n = int(np.count_nonzero(region == BROWN_ID))
            cream = int(np.count_nonzero(region == CREAM_ID))
            if gold < 3:
                continue
            x, y, w, h = x0 + cx0, y0 + cy0, cx1 - cx0, cy1 - cy0
            partial = x <= 0 or y <= 0 or x + w >= w_img or y + h >= h_img
            if exclude is not None:
                ex, ey, ew, eh = exclude
                near = not (x + w < ex - 2 or x > ex + ew + 2 or y + h < ey - 2 or y > ey + eh + 2)
                partial |= near
            out.append(_Candidate((x, y, w, h), gold, brown_n, cream, _seam_score(region), partial,
                                  region))
        return out

    # -- classification -----------------------------------------------------------------------

    def _classify(self, classes: np.ndarray, cand: _Candidate, timestamp: float,
                  elevation: float | None = None) -> Detection3D | None:
        x, y, w, h = cand.bbox
        total = cand.gold + cand.brown + cand.cream
        brown_frac = cand.brown / total
        cream_frac = cand.cream / total
        aspect = w / h
        if not 0.18 <= aspect <= 3.5:          # upright opened lids seen edge-on are thin
            return None
        if self.method == "color":
            if brown_frac < 0.06 or cand.seam < 0.25:
                return None
            opened = cream_frac >= 0.05 or (_lid_is_upright(cand.region)
                                            and (elevation is None or elevation < 25.0))
            conf = min(1.0, 0.5 + cand.seam * 0.5)
            return Detection3D("chest_opened" if opened else "chest", cand.bbox, round(conf, 3),
                               timestamp, "color", partial=cand.partial)
        # hybrid: compare the candidate's class image with every reference view.
        region = cand.region
        best: tuple[float, Template3D] | None = None
        for t in self.templates.templates:
            if not 0.6 <= aspect / t.aspect <= 1.6 and not cand.partial:
                continue
            if elevation is not None and abs(t.elevation_deg - elevation) > 17.0:
                continue
            resized = cv2.resize(t.labels, (w, h), interpolation=cv2.INTER_NEAREST)
            either = (resized > 0) | (region > 0)
            n = int(np.count_nonzero(either))
            if n == 0:
                continue
            agree = int(np.count_nonzero((resized == region) & either))
            score = agree / n
            if best is None or score > best[0]:
                best = (score, t)
        colour_ok = (brown_frac >= 0.06 and cand.seam >= 0.25) or _lid_is_upright(cand.region)
        if best is None:
            return None
        score, t = best
        threshold = self.min_score - (0.1 if cand.partial and cand.seam >= 0.4 else 0.0)
        accepted = score >= threshold or (colour_ok and score >= 0.35)
        if not accepted or cand.brown < 2:
            return None
        if score >= 0.45:
            category = t.category                    # the matched view decides open/closed
        else:
            opened = cream_frac >= 0.05 or (_lid_is_upright(cand.region)
                                            and (elevation is None or elevation < 25.0))
            category = "chest_opened" if opened else "chest"
        if cream_frac >= 0.12:
            category = "chest_opened"                # the bright inside is unambiguous
        conf = min(1.0, 0.6 * score + 0.4 * min(1.0, cand.seam + (0.5 if colour_ok else 0.0)))
        return Detection3D(category, cand.bbox, round(conf, 3), timestamp, "hybrid", view=t.name,
                           width_m=t.width_m, height_m=t.height_m, partial=cand.partial)

    # -- pure template matching (baseline) -------------------------------------------------------

    def _detect_template(self, frame: np.ndarray, timestamp: float,
                         exclude: tuple[int, int, int, int] | None) -> list[Detection3D]:
        small = cv2.resize(frame, (frame.shape[1] // 2, frame.shape[0] // 2),
                           interpolation=cv2.INTER_AREA)
        if exclude is not None:
            x, y, w, h = (v // 2 for v in exclude)
            small[max(0, y):y + h, max(0, x):x + w] = 0
        views = [t for t in self.templates.templates if t.elevation_deg in (8.0, 20.0)
                 and t.name.split("_y")[1][:3] in ("000", "060", "090")]
        found: list[Detection3D] = []
        for t in views:
            for width in (10, 16, 26, 42):
                scale = width / t.bgr.shape[1]
                th = max(4, int(round(t.bgr.shape[0] * scale)))
                if th >= small.shape[0] or width >= small.shape[1]:
                    continue
                tmpl = cv2.resize(t.bgr, (width, th), interpolation=cv2.INTER_AREA)
                res = cv2.matchTemplate(small, tmpl, cv2.TM_CCOEFF_NORMED)
                ys, xs = np.nonzero(res >= 0.82)
                for yy, xx in zip(ys[:50], xs[:50], strict=True):
                    found.append(Detection3D(t.category, (int(xx) * 2, int(yy) * 2, width * 2, th * 2),
                                             float(min(1.0, res[yy, xx])), timestamp, "template",
                                             view=t.name, width_m=t.width_m, height_m=t.height_m))
        return _nms(found)


def _seam_score(region: np.ndarray) -> float:
    """Fraction of columns where brown lid pixels sit directly above gold body pixels."""
    brown = region == BROWN_ID
    gold = region == GOLD_ID
    if not brown.any() or not gold.any():
        return 0.0
    # brown at row r and gold within the next two rows below
    below = np.zeros_like(gold)
    below[:-1] |= gold[1:]
    below[:-2] |= gold[2:]
    seam_cols = np.any(brown & below, axis=0)
    gold_cols = np.any(gold, axis=0)
    return float(np.count_nonzero(seam_cols)) / max(1, int(np.count_nonzero(gold_cols)))


def _lid_is_upright(region: np.ndarray) -> bool:
    """Opened chests show a tall brown lid above the body (seen from low angles)."""
    rows_brown = np.nonzero(np.any(region == BROWN_ID, axis=1))[0]
    rows_gold = np.nonzero(np.any(region == GOLD_ID, axis=1))[0]
    if rows_brown.size == 0 or rows_gold.size == 0:
        return False
    return (rows_brown.max() - rows_brown.min() + 1) >= 0.9 * (rows_gold.max() - rows_gold.min() + 1)


def _nms(dets: list[Detection3D], threshold: float = 0.3) -> list[Detection3D]:
    kept: list[Detection3D] = []
    for d in sorted(dets, key=lambda d: (-d.confidence, d.bbox)):
        if all(iou(d.bbox, k.bbox) <= threshold for k in kept):
            kept.append(d)
    return kept

